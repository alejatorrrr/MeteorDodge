# Accented letters retain visible diacritics; lowercase deliberately uses capitals.
for ch in 'ÁÉÍÓÚÜÑáéíóúüñ':
    base=unicodedata.normalize('NFD',ch.upper())[0]
    accent=['00110','00100'] if ch.upper() not in 'ÑÜ' else ['01010','10100'] if ch.upper()=='Ñ' else ['01010','00000']
    patterns[ch]=accent+patterns[base]
for ch in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ': patterns[ch.lower()]=patterns[ch]
patterns['¡']=list(reversed(patterns['!']))
patterns['¿']=list(reversed(patterns['?']))
patterns['%']=['11001','11011','00010','00100','01000','11011','10011']
patterns['=']=['00000','11111','00000','00000','11111','00000','00000']
patterns["'"]=['01100','01100','01000']+['00000']*4
chars=sorted(patterns,key=ord)
names={ch:'uni%04X'%ord(ch) for ch in chars}
order=['.notdef']+[names[ch] for ch in chars]
fb=FontBuilder(1000,isTTF=True);fb.setupGlyphOrder(order)
glyphs={};metrics={}
for ch in ['.notdef']+chars:
    pen=TTGlyphPen(None)
    rows=patterns.get(ch,['11111','10001','10101','10101','10001','11111','00000'])
    for y,row in enumerate(rows):
        # Merge horizontal runs for compact, adjoining outlines.
        x=0
        while x<len(row):
            if row[x]!='1': x+=1;continue
            end=x+1
            while end<len(row) and row[end]=='1':end+=1
            left=40+x*130;right=40+end*130;bottom=(len(rows)-1-y)*100
            pen.moveTo((left,bottom));pen.lineTo((right,bottom));pen.lineTo((right,bottom+100));pen.lineTo((left,bottom+100));pen.closePath();x=end
    name=ch if ch=='.notdef' else names[ch]
    glyphs[name]=pen.glyph();metrics[name]=(790 if ch!=' ' else 440,40)
fb.setupGlyf(glyphs);fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=950,descent=-100)
fb.setupCharacterMap({ord(ch):names[ch] for ch in chars})
fb.setupNameTable({'familyName':'Meteor Arcade','styleName':'Regular','uniqueFontIdentifier':'MeteorArcade-1.0','fullName':'Meteor Arcade Regular','psName':'MeteorArcade-Regular','version':'Version 1.0','copyright':'Original Meteor Dodge project font. Free to use and modify with this project.'})
fb.setupOS2(sTypoAscender=950,sTypoDescender=-100,sTypoLineGap=100,usWinAscent=950,usWinDescent=100)
fb.setupPost();fb.setupMaxp()
out=Path(__file__).resolve().parents[1]/'app/src/main/assets/meteor-arcade.ttf';fb.save(out)
print(out.name,out.stat().st_size,'bytes',len(chars),'characters')
